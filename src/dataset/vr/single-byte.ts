/**
 * The single-byte character sets of `(0008,0005)` Specific Character Set, each decoded by its own
 * table, byte for byte, as PS3.5 and the ISO-IR registration of the set define it.
 *
 * The rules, from the pinned PS3.5:
 *
 * - The default repertoire is ISO-IR 6, the International Reference Version of ISO 646 (PS3.5
 *   section 6.1.2.1). It has no character at `0x80` to `0xFF`.
 * - The C0 control set is invoked in CL and G0 and G1 in GL and GR, and "characters from the C1
 *   set shall not be used" (PS3.5 section 6.1.1). No set here defines `0x80` to `0x9F`.
 * - A single-byte set of PS3.3 Table C.12-2 has ISO-IR 6 in G0 and its own set in G1, invoked in
 *   GR (PS3.5 section 6.1.2.3), except `ISO_IR 13`, which is JIS X 0201: ISO-IR 14 in G0 and
 *   ISO-IR 13 in G1. ISO-IR 14 is ISO-IR 6 with a YEN SIGN at `0x5C` and an OVERLINE at `0x7E`
 *   (PS3.5 section 6.1.2.3), and the `0x5C` byte still separates the Values of a multi-valued VR,
 *   whatever character it is.
 *
 * Each G1 table below is the Unicode Consortium's mapping file for the set (`MAPPINGS/ISO8859/`
 * `8859-1.TXT` to `8859-15.TXT`, `8859-11.TXT` for TIS 620, and `JIS0201.TXT`) at `0xA0` to
 * `0xFF`, except where the Unicode file maps a later edition than the one ISO-IR registered: the
 * Greek set ISO-IR 126 has no `0xA4`, `0xA5` or `0xAA` (the 2003 edition added them, registered as
 * ISO-IR 227), and the Hebrew set ISO-IR 138 has no `0xFD` or `0xFE` (the 1999 edition added them,
 * registered as ISO-IR 198). A byte the set leaves undefined is {@link NONE} and decodes as U+FFFD,
 * never as another set's character.
 *
 * These tables replace the WHATWG `TextDecoder` labels the reader used before: `latin1` and
 * `iso-8859-9` there are windows-1252 and windows-1254, `windows-874` adds nine characters at
 * `0x80` to `0x9F`, `shift_jis` reads two bytes as one character, and `iso-8859-7` and
 * `iso-8859-8` carry the later editions' additions.
 *
 * The tables and the term list are answered by functions rather than kept in module-level maps, so
 * every row is code a test runs.
 *
 * @module
 */

