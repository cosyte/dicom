/**
 * The character byte `byte` encodes in the G1 set ISO-IR `ir`, or `undefined` when the set does
 * not define it, `ir` is no single-byte G1 set, or the byte is below `0xA0` and so before the
 * table.
 *
 * @internal
 */
export function g1Character(ir: number, byte: number): string | undefined {
  const cp = g1CodePoints(ir)?.[byte - 0xa0];
  return cp === undefined || cp === NONE ? undefined : String.fromCharCode(cp);
}

