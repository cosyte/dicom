/**
 * Capture what a tree at a git ref outputs for every document of the output-equivalence corpus, as
 * one SHA-256 per document, committed as expectation data.
 *
 *     pnpm capture:output-digests                 # against origin/main
 *     pnpm capture:output-digests --base <ref>    # against any ref
 *
 * The corpus and the record of one document live in `_output-corpus.ts`, shared with
 * `output-equivalence.test.ts`, which recomputes each digest on head and requires it to be
 * identical. That is the evidence that a change meant to make the reader or the writer faster
 * changed no element, value, warning, error or written byte.
 *
 * The documents are built with head's own corpus code and only `src/` comes from the ref, so both
 * sides read exactly the same bytes. `git archive` is used rather than a worktree so the tree
 * cannot pick up an untracked file. Re-run at the same ref, the file comes back byte-identical.
 *
 * @module
 */

import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { digestOf, outputCorpus, recordOf, type OutputApi } from "./_output-corpus.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "..", "..");
const OUT = join(HERE, "__data__", "output-digests.json");

/** The ref to capture: `--base <ref>`, or `origin/main`. */
function baseRef(argv: readonly string[]): string {
  const at = argv.indexOf("--base");
  return at === -1 ? "origin/main" : (argv[at + 1] ?? "origin/main");
}

/** Materialize `src/` at `ref` into a temp directory and import it. */
async function loadBase(ref: string): Promise<{ api: OutputApi; dir: string }> {
  const dir = mkdtempSync(join(tmpdir(), "dicom-output-digests-"));
  const archive = execFileSync("git", ["archive", ref, "src"], {
    cwd: REPO,
    maxBuffer: 256 * 1024 * 1024,
    encoding: "buffer",
  });
  execFileSync("tar", ["-x", "-C", dir], { input: archive });
  const api = (await import(pathToFileURL(join(dir, "src", "index.ts")).href)) as OutputApi;
  return { api, dir };
}

async function main(): Promise<void> {
  const ref = baseRef(process.argv.slice(2));
  const sha = execFileSync("git", ["rev-parse", ref], { cwd: REPO, encoding: "utf8" }).trim();
  const { api, dir } = await loadBase(ref);
  try {
    const documents: Record<string, string> = {};
    for (const doc of outputCorpus()) {
      if (doc.name in documents) throw new Error(`two corpus documents are named ${doc.name}`);
      documents[doc.name] = digestOf(recordOf(api, doc));
    }
    const payload = {
      note: "Generated by test/equivalence/capture-output-digests.ts. Do not hand-edit: re-run it.",
      base: sha,
      documents,
    };
    writeFileSync(OUT, `${JSON.stringify(payload, null, 2)}\n`, "utf8");
    console.log(`captured ${String(Object.keys(documents).length)} digests at ${sha}`);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

await main();
